// Convert the supplied Invoca design-canvas exports into ordinary static HTML.
// The source slides and interactions stay intact; their editor runtime is not
// needed on the portfolio. Run again after updating the source decks.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const decks = [
  { slug: 'call-review', folder: 'CRC Case Study', file: 'Invoca Case Study.dc.html', title: 'Invoca Call Review Console' },
  { slug: 'ai-signals', folder: 'AI Signals Case Study', file: 'Invoca AI Signal Discovery.dc.html', title: 'Invoca AI Signal Training' }
];
const output = resolve(root, 'case-study-decks/content');
mkdirSync(output, { recursive: true });
for (const deck of decks) {
  const source = readFileSync(resolve(root, 'Decks', deck.folder, deck.file), 'utf8');
  const head = source.match(/<helmet>([\s\S]*?)<\/helmet>/)?.[1];
  const slides = source.match(/<x-import\b[^>]*>([\s\S]*?)<\/x-import>/)?.[1];
  const logic = source.match(/<script\b[^>]*data-dc-script[\s\S]*?>([\s\S]*?)<\/script>/)?.[1];
  if (!head || !slides || !logic || !logic.includes('class Component extends DCLogic')) {
    throw new Error(`Unexpected source format: ${deck.file}`);
  }
  // Use normal images for the filled editor slots; retain the original zoom hook.
  const content = slides.replace(/<image-slot\b([^>]*)><\/image-slot>/g, (_, attributes) => {
    const src = attributes.match(/\bsrc="([^"]*)"/)?.[1];
    if (!src) throw new Error(`Unfilled image slot in ${deck.file}`);
    const id = attributes.match(/\bid="([^"]*)"/)?.[1] || '';
    return `<img src="${src}" alt="${id === 'ted-headshot' ? 'Ted Potter' : 'Product design detail'}" data-zoom style="width:100%;height:100%;object-fit:cover;display:block">`;
  });
  const cleanHead = head.replace(/<script[\s\S]*?<\/script>/g, '').replace(/<template[\s\S]*?<\/template>/g, '').replace(/<meta name="ext-resource-dependency"[^>]*>/g, '');
  const html = `<!DOCTYPE html>
<!-- Generated by scripts/prepare-case-study-decks.mjs from the original in Decks/. -->
<html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1">
<title>${deck.title}</title><meta name="robots" content="noindex">
<base href="/Decks/${encodeURIComponent(deck.folder)}/">
${cleanHead}
<style>deck-stage:not(:defined){visibility:hidden}html,body{height:100%;overflow:hidden}</style>
</head><body>
<deck-stage width="1920" height="1080" no-rail>${content}</deck-stage>
<script src="./deck-stage.js"></script>
<script>${logic.replace('class Component extends DCLogic', 'class Component')}
const presentation = new Component();
presentation.componentDidMount();
</script></body></html>`;
  writeFileSync(resolve(output, `${deck.slug}.html`), html);
  console.log(`${deck.slug}: ${[...slides.matchAll(/<section\b/g)].length} slides prepared`);
}
